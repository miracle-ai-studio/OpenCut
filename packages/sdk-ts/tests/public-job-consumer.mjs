import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { OpenCutClient, publicJobResult, JobCompletionError, OpenCutApiError } from "@opencut/sdk";
const [baseUrl, tokenFile, video, jobsFile] = process.argv.slice(2);
const client = new OpenCutClient({ baseUrl, token: readFileSync(tokenFile, "utf8").trim() });
const accepted = await client.submitJob({ kind: "media.probe", idempotency_key: "ts-public-probe", input: { input: video } });
assert.ok(!("input" in accepted));
const completed = await client.waitForPublicJob(accepted.job_id);
assert.ok(publicJobResult(completed, "media.probe").streams.some(s => s.codec_type === "video"));
assert.throws(() => publicJobResult(completed, "render.project"), TypeError);
const existing = JSON.parse(readFileSync(jobsFile, "utf8"));
const rendered = existing.find(j => j.kind === "render.project");
const reference = rendered.artifacts[0];
const response = await client.downloadArtifact(reference);
assert.equal(createHash("sha256").update(Buffer.from(await response.arrayBuffer())).digest("hex"), reference.content_hash);
const unavailable = structuredClone(reference);
unavailable.content_hash = "0".repeat(64); unavailable.artifact_id = `artifact:${reference.job_id}:${unavailable.content_hash}`;
await assert.rejects(client.downloadArtifact(unavailable), error => error instanceof OpenCutApiError && error.code === "NOT_FOUND");
const failed = await client.submitJob({ kind: "media.probe", idempotency_key: "ts-public-failed", input: { input: `${video}.missing` } });
await assert.rejects(client.waitForPublicJob(failed.job_id), error => error instanceof JobCompletionError && error.code === "JOB_FAILED" && error.job.failure && !("error" in error.job));
assert.equal((await client.cancelPublicJob(completed.job_id)).state, "succeeded");
console.log("Installed TS SDK uses public submission/wait/cancellation, typed result narrowing and authenticated artifact streams.");
