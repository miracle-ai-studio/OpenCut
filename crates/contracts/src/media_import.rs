//! Versioned media binding intent, separate from frozen visual operations.
use crate::{
    FrameRate,
    project_v3_ops::{ApplyV3Project, VisualOperation},
};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct MediaBindingV1 {
    /// Published media resource in this project; never a native path.
    pub media_id: String,
    pub replace_asset_id: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct MediaImportRequestV1 {
    pub project_id: String,
    pub expected_revision: String,
    /// Captured active scene for the frame-rate decision and optional placement.
    pub sequence_id: String,
    pub idempotency_key: String,
    pub label: String,
    pub media: Vec<MediaBindingV1>,
    /// Explicit placement intent; asset edits and settings are generated by the use case.
    pub operations: Vec<VisualOperation>,
    pub ripple: bool,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct MediaImportPlanV1 {
    /// Submit unchanged through visual apply; binding, placement and FPS are atomic.
    pub transaction: ApplyV3Project,
    pub previous_fps: FrameRate,
    /// None when the imported videos do not require a raise.
    pub raised_fps: Option<FrameRate>,
}
