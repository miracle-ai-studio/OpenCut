//! Pure import planning over a fixed document and host-authorized media resources.
use opencut_contracts::{
    Asset, AssetKind, EditorError, FrameRate, Operation,
    media_import::{MediaImportPlanV1, MediaImportRequestV1},
    project_v3::ProjectSnapshotV3,
    project_v3_ops::VisualOperation,
    timeline_edit::{ClassicCommandV1, ClassicEditRequestV1},
};
use std::collections::BTreeSet;

fn invalid(message: &str) -> EditorError {
    EditorError::new("INVALID_ARGUMENT", message)
}

pub fn validate(input: &MediaImportRequestV1) -> Result<(), EditorError> {
    let mut media = BTreeSet::new();
    let mut replacements = BTreeSet::new();
    if input.project_id.trim().is_empty()
        || input.expected_revision.trim().is_empty()
        || input.sequence_id.trim().is_empty()
        || input.idempotency_key.trim().is_empty()
        || input.label.trim().is_empty()
        || input.media.is_empty()
        || input.media.len() > 60
        || input.media.iter().any(|b| {
            b.media_id.trim().is_empty()
                || !media.insert(&b.media_id)
                || b.replace_asset_id
                    .as_ref()
                    .is_some_and(|id| id.trim().is_empty() || !replacements.insert(id))
        })
    {
        return Err(invalid(
            "Choose 1 to 60 distinct published media resources and replacement targets",
        ));
    }
    if input.operations.iter().any(|op| {
        matches!(
            op,
            VisualOperation::Base {
                operation: Operation::BindAsset { .. }
                    | Operation::ReplaceAsset { .. }
                    | Operation::RemoveAsset { .. }
                    | Operation::UpdateSequenceSettings { .. }
            }
        )
    }) {
        return Err(invalid(
            "Media binding and settings must be generated by the import planner",
        ));
    }
    Ok(())
}

fn greater(a: &FrameRate, b: &FrameRate) -> bool {
    u64::from(a.numerator) * u64::from(b.denominator)
        > u64::from(b.numerator) * u64::from(a.denominator)
}

const STANDARD_IMPORT_FRAME_RATES: [(u32, u32); 10] = [
    (24000, 1001),
    (24, 1),
    (25, 1),
    (30000, 1001),
    (30, 1),
    (48, 1),
    (50, 1),
    (60000, 1001),
    (60, 1),
    (120, 1),
];

/// Normalize an unrounded Classic packet observation, preserving the original
/// floating comparison/tolerance and positive Math.round semantics.
pub fn normalize_classic_packet_fps(rate: f64) -> Result<FrameRate, EditorError> {
    if !rate.is_finite() || rate <= 0.0 || rate > f64::from(u32::MAX) {
        return Err(invalid(
            "Classic packet frame rate is outside the project format",
        ));
    }
    for (n, d) in STANDARD_IMPORT_FRAME_RATES {
        if (rate - f64::from(n) / f64::from(d)).abs() <= 0.01 {
            return Ok(FrameRate {
                numerator: n,
                denominator: d,
            });
        }
    }
    if rate.fract() == 0.0 {
        return Ok(FrameRate {
            numerator: rate as u32,
            denominator: 1,
        });
    }
    let mut n = (rate * 1_000_000.0).round() as u64;
    if n == 0 {
        return Err(invalid("Classic packet frame rate rounds to zero"));
    }
    let mut d = 1_000_000_u64;
    let (mut a, mut b) = (n, d);
    while b != 0 {
        (a, b) = (b, a % b);
    }
    n /= a;
    d /= a;
    Ok(FrameRate {
        numerator: u32::try_from(n)
            .map_err(|_| invalid("Imported frame rate exceeds the project format"))?,
        denominator: d as u32,
    })
}

// Classic fps/utils.ts ordered normalization within 0.01 fps, without floating time.
pub(crate) fn normalize_import_fps(rate: &FrameRate) -> Result<FrameRate, EditorError> {
    if rate.numerator == 0 || rate.denominator == 0 {
        return Err(invalid("Imported frame rate must be positive"));
    }
    for (n, d) in STANDARD_IMPORT_FRAME_RATES {
        let delta = (i128::from(rate.numerator) * i128::from(d)
            - i128::from(n) * i128::from(rate.denominator))
        .abs();
        if delta * 100 <= i128::from(rate.denominator) * i128::from(d) {
            return Ok(FrameRate {
                numerator: n,
                denominator: d as u32,
            });
        }
    }
    // Classic's arbitrary 1e6 denominator and positive Math.round, then reduce.
    let mut n = (u64::from(rate.numerator) * 1_000_000 + u64::from(rate.denominator) / 2)
        / u64::from(rate.denominator);
    let mut d = 1_000_000_u64;
    let (mut a, mut b) = (n, d);
    while b != 0 {
        (a, b) = (b, a % b);
    }
    n /= a;
    d /= a;
    Ok(FrameRate {
        numerator: u32::try_from(n)
            .map_err(|_| invalid("Imported frame rate exceeds the project format"))?,
        denominator: d as u32,
    })
}

pub fn raised_fps(current: &FrameRate, assets: &[Asset]) -> Result<Option<FrameRate>, EditorError> {
    let highest = assets
        .iter()
        .filter(|a| a.kind == AssetKind::Video)
        .filter_map(|a| {
            a.metadata
                .get("frame_rate")
                .and_then(|v| serde_json::from_value::<FrameRate>(v.clone()).ok())
        })
        .filter(|r| r.numerator > 0 && r.denominator > 0)
        .reduce(|a, b| if greater(&b, &a) { b } else { a });
    if let Some(rate) = highest.filter(|r| greater(r, current)) {
        let rate = normalize_import_fps(&rate)?;
        // Tolerance rounding must never lower an explicitly chosen nonstandard FPS.
        if greater(&rate, current) {
            return Ok(Some(rate));
        }
    }
    Ok(None)
}

pub fn plan(
    snapshot: &ProjectSnapshotV3,
    input: &MediaImportRequestV1,
    assets: &[Asset],
) -> Result<MediaImportPlanV1, EditorError> {
    validate(input)?;
    if snapshot.project.base.id != input.project_id {
        return Err(invalid("Import project scope differs"));
    }
    if snapshot.revision != input.expected_revision {
        return Err(EditorError::new(
            "REVISION_CONFLICT",
            "Import revision differs",
        ));
    }
    let scene = snapshot
        .project
        .base
        .sequences
        .iter()
        .find(|s| s.id == input.sequence_id)
        .ok_or_else(|| EditorError::new("NOT_FOUND", "Import scene no longer exists"))?;
    if assets.len() != input.media.len()
        || assets
            .iter()
            .zip(&input.media)
            .any(|(a, b)| a.id != b.media_id)
    {
        return Err(invalid(
            "Resolved media differs from the authorized resources",
        ));
    }
    let mut operations = Vec::new();
    for (asset, binding) in assets.iter().zip(&input.media) {
        let mut asset = asset.clone();
        // The immutable media observation retains packet provenance. Frozen
        // V3 project assets keep their historical header-only metadata shape.
        asset
            .metadata
            .remove(opencut_media_contracts::CLASSIC_PACKET_RATE_METADATA_KEY_V1);
        let operation = if let Some(id) = &binding.replace_asset_id {
            let old = snapshot
                .project
                .base
                .assets
                .iter()
                .find(|a| &a.id == id)
                .ok_or_else(|| {
                    EditorError::new("NOT_FOUND", "Replacement target no longer exists")
                })?;
            if old.kind != asset.kind {
                return Err(invalid("Replacement media must have the same type"));
            }
            asset.id = id.clone();
            Operation::ReplaceAsset { asset }
        } else {
            Operation::BindAsset { asset }
        };
        operations.push(VisualOperation::Base { operation });
    }
    operations.extend(input.operations.clone());
    let raised_fps = raised_fps(&scene.fps, assets)?;
    if let Some(fps) = &raised_fps {
        operations.push(VisualOperation::Base {
            operation: Operation::UpdateSequenceSettings {
                sequence_id: scene.id.clone(),
                name: None,
                width: None,
                height: None,
                fps: Some(fps.clone()),
            },
        });
    }
    let result = crate::timeline_edit::classic::plan(
        snapshot,
        &ClassicEditRequestV1 {
            project_id: input.project_id.clone(),
            expected_revision: input.expected_revision.clone(),
            sequence_id: input.sequence_id.clone(),
            idempotency_key: input.idempotency_key.clone(),
            label: input.label.clone(),
            ripple: input.ripple,
            command: ClassicCommandV1::Apply { operations },
        },
    )?;
    Ok(MediaImportPlanV1 {
        transaction: result.plan.transaction,
        previous_fps: scene.fps.clone(),
        raised_fps,
    })
}

