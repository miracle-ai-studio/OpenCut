#!/usr/bin/env python3
"""Additive V3 source pins from existing cache only; no network or V1 regeneration.

This is source-data generation, not native/parser/browser acceptance. Every
admitted name pair is explicit, and bytes/notice remain unchanged. Metadata and
checksum failures are recorded for a separate proof-carrying derivation.
"""
import argparse
import hashlib
import json
import re
import urllib.parse
from pathlib import Path
import generate as original

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates/editor-application/src/font_catalog_v3"
ALIASES = {
    "Fjord One": "Fjord", "Headland One": "HeadlandOne",
    "IM Fell Double Pica": "IM FELL Double Pica", "IM Fell Double Pica SC": "IM FELL Double Pica SC",
    "IM Fell DW Pica": "IM FELL DW Pica", "IM Fell DW Pica SC": "IM FELL DW Pica SC",
    "IM Fell English": "IM FELL English", "IM Fell English SC": "IM FELL English SC",
    "IM Fell French Canon": "IM FELL French Canon", "IM Fell French Canon SC": "IM FELL French Canon SC",
    "IM Fell Great Primer": "IM FELL Great Primer", "IM Fell Great Primer SC": "IM FELL Great Primer SC",
    "Nanum Gothic": "NanumGothic", "Nanum Gothic Coding": "NanumGothicCoding",
    "Nanum Myeongjo": "NanumMyeongjo", "Nanum Pen Script": "Nanum Pen",
    "Nova Mono": "NovaMono", "Poetsen One": "PoetsenOne",
    "Saira Extra Condensed": "Saira ExtraCondensed", "Saira Semi Condensed": "Saira SemiCondensed",
    "Sirin Stencil": "SirinStencil", "Supermercado One": "Supermercado",
}
PROFILES = {"static_outline": "StaticOutline", "colr_v0": "ColrV0", "colr_v1": "ColrV1", "monochrome_bitmap": "MonochromeBitmap"}

def cached(path, cache, tree):
    entry = tree[path]
    data = (cache / path).read_bytes()
    blob = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
    if entry["type"] != "blob" or len(data) != entry["size"] or blob != entry["sha"]:
        raise ValueError(f"Cached source differs from fixed Google tree: {path}")
    return data

def emit(records, target):
    lines = ["// Generated by scripts/font-catalog/generate_catalog_v3.py; source bytes remain external.", "&["]
    for record in sorted(records, key=lambda value: value["source"]["catalog_id"]):
        pin = record["source"]
        if hashlib.sha256(pin["license_notice"].encode()).hexdigest() != pin["license_sha256"]:
            raise ValueError("License notice does not match its pin")
        notice = OUT / "licenses" / (pin["license_sha256"] + ".txt")
        notice.parent.mkdir(parents=True, exist_ok=True)
        notice.write_bytes(pin["license_notice"].encode())
        lines += ["    StaticFontEntryV3 {", "        approved: ApprovedFontSourceV3 {", "            source: PinnedFontSourceV1 {"]
        for key in ("catalog_id", "family", "weight", "style", "source_commit", "source_url", "content_hash", "size_bytes", "license_url", "license_sha256", "license_identifier", "license_notice", "attribution"):
            if key == "style": value = "opencut_contracts::project_v4::FontStyleV4::" + {"normal": "Normal", "italic": "Italic"}[pin[key]]
            elif key == "license_notice": value = f'include_str!("licenses/{pin["license_sha256"]}.txt")'
            else: value = json.dumps(pin[key], ensure_ascii=False)
            lines.append(f"                {key}: {value},")
        lines += ["            },", f'            render_profile: FontRenderProfileV3::{PROFILES[record["render_profile"]]},', "        },",
                  f'        display_family: {json.dumps(record["display_family"], ensure_ascii=False)},',
                  "        alias_reason: " + ("None" if record.get("alias_reason") is None else f'Some({json.dumps(record["alias_reason"],ensure_ascii=False)})') + ",", "    },"]
    lines.append("]")
    target.write_text("\n".join(lines) + "\n")

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tree", type=Path, required=True)
    parser.add_argument("--cache", type=Path, required=True)
    args = parser.parse_args()
    if ROOT == args.cache.resolve() or ROOT in args.cache.resolve().parents:
        raise ValueError("Source cache must remain outside the repository")
    raw_tree = json.loads(args.tree.read_text())
    if raw_tree.get("truncated") or raw_tree.get("sha") != original.COMMIT:
        raise ValueError("Expected complete pinned Google tree")
    tree = {entry["path"]: entry for entry in raw_tree["tree"]}
    report = json.loads((original.OUT / "catalog_source_report.json").read_text())
    decisions, records = [], []
    for failure in report["failures"]:
        reason = failure["reason"]
        if "mismatch" not in reason: continue
        family, path = failure["family"], failure["path"]
        data = cached(path, args.cache, tree)
        decision = dict(failure, content_hash=original.digest(data), size_bytes=len(data))
        if reason == "native table checksum mismatch":
            decision.update(decision="requires_explicit_checksum_derivation", admitted=False)
            decisions.append(decision); continue
        native, weight, style = original.face(data)
        decision.update(native_family=native, actual_weight=weight, actual_style=style)
        if reason == "declared weight/style/size mismatch":
            decision.update(decision="requires_explicit_metadata_derivation", admitted=False)
            decisions.append(decision); continue
        if family == "Inconsolata" and native == "Ligconsolata":
            decision.update(decision="distinct_ligature_variant_not_classic_alias", admitted=False)
            decisions.append(decision); continue
        if ALIASES.get(family) != native:
            # The pinned Pushster directory actually contains the existing
            # Lobster font. It must not be silently certified as a spelling alias.
            decision.update(decision="source_identity_differs_from_classic_family", admitted=False)
            if family=="Pushster" and native=="Lobster":
                decision["official_file_history"]={"commit":"a2e33f35fddfb580f42350a8dd78230d2b41c7bb","message":"Create a test font, temporarily, to test the push process.","same_bytes_as":"google-lobster-regular-v1"}
            decisions.append(decision); continue
        if weight not in (400, 700): raise ValueError("Alias changes unsupported face weight")
        license_path = "/".join(path.split("/")[:2]) + ("/OFL.txt" if path.startswith("ofl/") else "/LICENSE.txt")
        license_data = cached(license_path, args.cache, tree)
        notice = license_data.decode("utf-8")
        identifier = "OFL-1.1" if license_path.endswith("OFL.txt") else "Apache-2.0"
        suffix = {(400,"normal"):"regular",(700,"normal"):"bold",(400,"italic"):"italic",(700,"italic"):"bold-italic"}[(weight,style)]
        pin = dict(catalog_id=f"google-{original.norm(family)}-{suffix}-alias-v3",family=native,weight=weight,style=style,
                   source_commit=original.COMMIT,source_url=original.BASE+urllib.parse.quote(path),content_hash=original.digest(data),size_bytes=len(data),
                   license_url=original.BASE+urllib.parse.quote(license_path),license_sha256=original.digest(license_data),license_identifier=identifier,
                   license_notice=notice,attribution=re.split(r"\r?\n\r?\n",notice)[0].rstrip() if identifier == "OFL-1.1" else "")
        explanation = f'Classic labels this family "{family}"; the original pinned font declares "{native}". Bytes and native family are preserved.'
        records.append(dict(source=pin,display_family=family,render_profile="static_outline",alias_reason=explanation,source_path=path))
        decision.update(decision="explicit_label_alias_original_bytes",admitted=True,catalog_id=pin["catalog_id"])
        decisions.append(decision)
    (OUT / "static_source_pins.json").write_text(json.dumps(records, ensure_ascii=False, indent=2)+"\n")
    (OUT / "static_source_decisions.json").write_text(json.dumps(dict(source_commit=original.COMMIT,scope="source_generation_only_not_native_acceptance",decisions=decisions),ensure_ascii=False,indent=2)+"\n")
    emit(records, OUT / "static_generated.rs")
    colors = json.loads((OUT / "color_source_pins.json").read_text())
    emit(colors, OUT / "color_generated.rs")
    print(json.dumps(dict(static_aliases=len(records),color_and_bitmap=len(colors),decisions=len(decisions))))

if __name__ == "__main__": main()
