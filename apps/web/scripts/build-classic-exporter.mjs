import { build } from "vite";
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
const root = path.resolve(import.meta.dirname, "..");
const result = await build({
  configFile: false,
  root,
  publicDir: false,
  logLevel: "error",
  build: {
    write: false,
    minify: true,
    lib: {
      entry: path.join(
        root,
        "src/editor/workspace/classic/old-origin-exporter.ts",
      ),
      name: "OpenCutClassicExporter",
      formats: ["iife"],
    },
  },
});
const output = (Array.isArray(result) ? result[0] : result).output.find(
  (item) => item.type === "chunk",
);
if (!output) throw new Error("Classic exporter bundle is missing");
const content =
  "// Generated read-only old-origin Classic exporter. Run build-classic-exporter.mjs to update.\n" +
  output.code;
const hash = createHash("sha256").update(content).digest("hex");
const basename = `classic-exporter-${hash.slice(0, 16)}.js`;
const assets = path.join(root, "public/assets");
const target = path.join(assets, basename);
const declaration = path.join(
  root,
  "src/editor/workspace/classic/exporter.generated.ts",
);
const reference = `// Generated by scripts/build-classic-exporter.mjs.\nexport const classicExporterUrl = "/assets/${basename}";\n`;
if (process.argv.includes("--check")) {
  if (
    (await fs.readFile(target, "utf8")) !== content ||
    (await fs.readFile(declaration, "utf8")) !== reference
  )
    throw new Error("Classic exporter is stale");
} else {
  await fs.mkdir(assets, { recursive: true });
  for (const file of await fs.readdir(assets))
    if (/^classic-exporter-[a-f0-9]{16}\.js$/.test(file) && file !== basename)
      await fs.unlink(path.join(assets, file));
  await fs.writeFile(target, content);
  await fs.writeFile(declaration, reference);
}
console.log("Classic old-origin exporter generated and self-contained.");
